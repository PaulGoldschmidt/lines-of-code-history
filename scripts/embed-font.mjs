// Regenerates src/sketch-font.ts from assets/fonts/PatrickHand-Regular-latin.woff2.
// The font is embedded in sketch-style SVGs as a data URI because GitHub's image proxy
// does not let an SVG load external resources.
import { readFileSync, writeFileSync } from 'node:fs';

const woff2 = readFileSync(new URL('../assets/fonts/PatrickHand-Regular-latin.woff2', import.meta.url));
const out = `// Generated by scripts/embed-font.mjs. Do not edit by hand.
// Patrick Hand by Patrick Wagesreiter, SIL Open Font License 1.1 (assets/fonts/PatrickHand-OFL.txt).
// Latin subset as served by Google Fonts, ${woff2.length} bytes of WOFF2.
export const SKETCH_FONT_FAMILY = 'Patrick Hand';
export const SKETCH_FONT_DATA_URI = 'data:font/woff2;base64,${woff2.toString('base64')}';
`;
writeFileSync(new URL('../src/sketch-font.ts', import.meta.url), out);
console.log(`wrote src/sketch-font.ts (${out.length} bytes)`);
